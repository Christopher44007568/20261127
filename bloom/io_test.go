func TestPPM16RoundTrip(t *testing.T) {
	im, err := NewImage(2, 1)
	if err != nil {
		t.Fatal(err)
	}
	im.Pixels[0] = RGB{0, 0.5, 1}
	im.Pixels[1] = RGB{1.0 / 255, 128.0 / 255, 254.0 / 255}
	path := filepath.Join(t.TempDir(), "roundtrip.ppm")
	if err := WritePPM16(path, im); err != nil {
		t.Fatal(err)
	}
	got, err := ReadPPM(path)
	if err != nil {
		t.Fatal(err)
	}
	if got.Width != 2 || got.Height != 1 || got.MaxVal != 65535 {
		t.Fatalf("unexpected PPM header: %dx%d max=%d", got.Width, got.Height, got.MaxVal)
	}
	for i := range im.Pixels {
		for _, pair := range [][2]float64{
			{im.Pixels[i].R, got.Pixels[i].R},
			{im.Pixels[i].G, got.Pixels[i].G},
			{im.Pixels[i].B, got.Pixels[i].B},
		} {
			want := float64(PPM16Code(pair[0])) / 65535
			if pair[1] != want {
				t.Fatalf("pixel %d sample = %.17g, want %.17g", i, pair[1], want)
			}
		}
	}
}

func TestPPMReaderHandlesCommentsAndCRLF(t *testing.T) {
	path := filepath.Join(t.TempDir(), "commented.ppm")
	data := []byte("P6\r\n# generated by test\r\n2 1\r\n255\r\n" +
		string([]byte{0, 127, 255, 255, 1, 2}))
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := ReadPPM(path)
	if err != nil {
		t.Fatal(err)
	}
	if got.MaxVal != 255 || len(got.Pixels) != 2 {
		t.Fatalf("unexpected PPM: %+v", got)
	}
	if math.Abs(got.Pixels[0].G-127.0/255) > 1e-12 || got.Pixels[1].B != 2.0/255 {
		t.Fatalf("unexpected PPM samples: %+v", got.Pixels)
	}
}

func TestPFMRoundTrip(t *testing.T) {
	im, err := NewImage(2, 2)
	if err != nil {
		t.Fatal(err)
	}
	im.Pixels[0] = RGB{0.1, 1.5, 64}
	im.Pixels[1] = RGB{-0.25, 2, 3}
	im.Pixels[2] = RGB{0, 0.5, 65504}
	im.Pixels[3] = RGB{1e-6, 12.5, 150000}
	path := filepath.Join(t.TempDir(), "roundtrip.pfm")
	if err := WritePFM(path, im); err != nil {
		t.Fatal(err)
	}
	got, err := ReadPFM(path)
	if err != nil {
		t.Fatal(err)
	}
	if got.Width != im.Width || got.Height != im.Height {
		t.Fatalf("unexpected PFM dimensions %dx%d", got.Width, got.Height)
	}
	for i := range im.Pixels {
		for _, pair := range [][2]float64{
			{im.Pixels[i].R, got.Pixels[i].R},
			{im.Pixels[i].G, got.Pixels[i].G},
			{im.Pixels[i].B, got.Pixels[i].B},
		} {
			if math.Abs(pair[0]-pair[1]) > 1e-6*math.Max(1, math.Abs(pair[0])) {
				t.Fatalf("pixel %d PFM value = %g, want %g", i, pair[1], pair[0])
			}
		}
	}
}

func TestPNGArtifactsDecode(t *testing.T) {
	im, err := NewImage(4, 3)
	if err != nil {
		t.Fatal(err)
	}
	for i := range im.Pixels {
		im.Pixels[i] = RGB{float64(i) / 8, 0.5, 2}
	}
	dir := t.TempDir()
	comparison := filepath.Join(dir, "compare.png")
	if err := WriteComparisonPNG(comparison, im, im); err != nil {
		t.Fatal(err)
	}
	heatmap := filepath.Join(dir, "heat.png")
	errImage, err := NewImage(4, 3)
	if err != nil {
		t.Fatal(err)
	}
	for i := range errImage.Pixels {
		errImage.Pixels[i] = RGB{float64(i) / 100, 0, 0}
	}
	if err := WriteQuantizationHeatmap(heatmap, errImage, 0.1); err != nil {
		t.Fatal(err)
	}
	assertPNGSize(t, comparison, 12, 3)
	assertPNGSize(t, heatmap, 4, 15)
}

func assertPNGSize(t *testing.T, path string, wantW, wantH int) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(data, []byte("\x89PNG\r\n\x1a\n")) {
		t.Fatalf("%s is not a PNG", path)
	}
	im, format, err := image.Decode(bytes.NewReader(data))
	if err != nil {
		t.Fatal(err)
	}
	if format != "png" {
		t.Fatalf("%s decoded as %s", path, format)
	}
	bounds := im.Bounds()
	if bounds.Dx() != wantW || bounds.Dy() != wantH {
		t.Fatalf("%s is %dx%d, want %dx%d", path, bounds.Dx(), bounds.Dy(), wantW, wantH)
	}
}
