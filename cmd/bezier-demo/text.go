func drawText(c *bezierstroke.Canvas, x, y, scale int, text string, fg color.RGBA) {
	text = strings.ToUpper(text)
	cursor := x
	for i := 0; i < len(text); i++ {
		glyph, ok := font5x7[text[i]]
		if !ok {
			glyph = font5x7['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] != '1' {
					continue
				}
				px0 := cursor + col*scale
				py0 := y + row*scale
				for py := py0; py < py0+scale; py++ {
					for px := px0; px < px0+scale; px++ {
						if px < 0 || px >= c.W || py < 0 || py >= c.H {
							continue
						}
						off := py*c.Pix.Stride + px*4
						c.Pix.Pix[off+0] = fg.R
						c.Pix.Pix[off+1] = fg.G
						c.Pix.Pix[off+2] = fg.B
						c.Pix.Pix[off+3] = 255
					}
				}
			}
		}
		cursor += 6 * scale
	}
}
