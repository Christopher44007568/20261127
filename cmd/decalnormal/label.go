package main

// Bitmap font: 5x7 glyphs for the characters needed by the image labels.
// Each glyph is seven rows; the low 5 bits of each row are its columns.
var font5x7 = map[rune][7]byte{
	' ': {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
	'A': {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},
	'C': {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E},
	'D': {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E},
	'E': {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F},
	'G': {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F},
	'I': {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x1F},
	'L': {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},
	'M': {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11},
	'N': {0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11},
	'O': {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},
	'R': {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},
	'T': {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},
	'V': {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},
	'Y': {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04},
	'(': {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02},
	')': {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08},
	'-': {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00},
	':': {0x00, 0x04, 0x00, 0x00, 0x00, 0x04, 0x00},
}

// drawText renders an uppercase label centered horizontally within the
// span [x0, x1), with a dark plate behind it for readability.
func (im *FloatImage) drawText(text string, x0, x1, topY int, color Vec3) {
	const (
		scale    = 2
		glyphW   = 5
		glyphH   = 7
		spacing  = 1
		platePad = 4
	)
	textW := len(text)*(glyphW+spacing)*scale - spacing*scale
	startX := x0 + (x1-x0-textW)/2
	plateH := glyphH*scale + platePad*2

	for y := topY; y < topY+plateH && y < im.H; y++ {
		for x := x0; x < x1 && x < im.W; x++ {
			im.set(x, y, v3(0.015, 0.015, 0.02))
		}
	}

	cx := startX
	for _, r := range text {
		glyph, ok := font5x7[r]
		if !ok {
			glyph = font5x7[' ']
		}
		for row := 0; row < glyphH; row++ {
			for col := 0; col < glyphW; col++ {
				if glyph[row]&(1<<(glyphW-1-col)) == 0 {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						px := cx + col*scale + sx
						py := topY + platePad + row*scale + sy
						if px >= 0 && px < im.W && py >= 0 && py < im.H {
							im.set(px, py, color)
						}
					}
				}
			}
		}
		cx += (glyphW + spacing) * scale
	}
}
