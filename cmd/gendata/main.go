// Command gendata embeds the downloaded spectral datasets into Go source.
//
// Inputs (fetched once, URLs documented in README.md):
//   - cmf.h: CIE 1931 standard observer, 5 nm steps, 360-780 nm
//   - fe.yml: Johnson & Christy (1974) Fe optical constants n,k (um)
//   - dseries.py: CIE D-illuminant basis functions S0/S1/S2
//
// Output: internal/optconst/data_gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type sample struct {
	lambda float64
	vals   []float64
}

func fatal(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var floatRe = regexp.MustCompile(`[-+]?\d*\.\d+(?:[eE][-+]?\d+)?|\d+`)

// parseCMF reads rows like "{ 0.000130f, 0.000004f, 0.000606f }, // 360 nm".
func parseCMF(path string, loNM, hiNM float64) []sample {
	f, err := os.Open(path)
	fatal(err)
	defer f.Close()

	var rows []sample
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if !strings.Contains(line, "{") {
			continue
		}
		nums := floatRe.FindAllString(line, -1)
		if len(nums) < 4 {
			continue
		}
		lambda, err := strconv.ParseFloat(nums[len(nums)-1], 64)
		fatal(err)
		if lambda < loNM || lambda > hiNM {
			continue
		}
		row := sample{lambda: lambda, vals: make([]float64, 3)}
		for i := 0; i < 3; i++ {
			row.vals[i], err = strconv.ParseFloat(nums[i], 64)
			fatal(err)
		}
		rows = append(rows, row)
	}
	fatal(sc.Err())
	return rows
}

// parseFeNK reads the tabulated n,k block of a refractiveindex.info YAML file.
func parseFeNK(path string, loNM, hiNM float64) []sample {
	f, err := os.Open(path)
	fatal(err)
	defer f.Close()

	var rows []sample
	inData := false
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "    data:") {
			inData = true
			continue
		}
		if inData {
			if line != "" && line[0] != ' ' && line[0] != '\t' {
				break
			}
			fields := strings.Fields(line)
			if len(fields) != 3 {
				continue
			}
			wlUM, err := strconv.ParseFloat(fields[0], 64)
			fatal(err)
			lambda := wlUM * 1000.0
			if lambda < loNM || lambda > hiNM {
				continue
			}
			row := sample{lambda: lambda, vals: make([]float64, 2)}
			for i := 0; i < 2; i++ {
				row.vals[i], err = strconv.ParseFloat(fields[i+1], 64)
				fatal(err)
			}
			rows = append(rows, row)
		}
	}
	fatal(sc.Err())
	return rows
}

func emitTable(b *strings.Builder, name string, rows []sample, width int) {
	fmt.Fprintf(b, "var %s = []struct{ Lambda float64; Vals []float64 }{\n", name)
	for _, r := range rows {
		fmt.Fprintf(b, "\t{%g, []float64{", r.lambda)
		for i, v := range r.vals {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%g", v)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\n")
	_ = width
}

func main() {
	cmfPath := envOr("CMF_FILE", "/tmp/cmf.h")
	fePath := envOr("FE_FILE", "/tmp/fe.yml")
	daylightPath := envOr("DAYLIGHT_FILE", "/tmp/dseries.py")
	outPath := envOr("OUT_FILE", "internal/optconst/data_gen.go")

	lo, hi := 380.0, 780.0
	cmf := parseCMF(cmfPath, lo, hi)
	fe := parseFeNK(fePath, lo, hi)
	if len(cmf) != 81 || len(fe) < 10 {
		fatal(fmt.Errorf("unexpected row counts: cmf=%d fe=%d", len(cmf), len(fe)))
	}
	daylight := parseDaylight(daylightPath)
	if len(daylight) != 107 {
		fatal(fmt.Errorf("unexpected daylight rows: %d", len(daylight)))
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gendata; DO NOT EDIT.\n\n")
	b.WriteString("package optconst\n\n")
	emitTable(&b, "cmf1931Table", cmf, 3)
	emitTable(&b, "feJohnsonTable", fe, 2)
	emitDaylight(&b, daylight)

	err := os.WriteFile(outPath, []byte(b.String()), 0o644)
	fatal(err)
	fmt.Printf("wrote %s (cmf=%d rows, fe=%d rows, daylight=%d rows)\n",
		outPath, len(cmf), len(fe), len(daylight))
}

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// parseDaylight extracts the S0/S1/S2 basis dicts from the colour-science
// source file. Each block begins with `    "Sn": {` and ends with `    },`.
func parseDaylight(path string) []sample {
	f, err := os.Open(path)
	fatal(err)
	defer f.Close()

	blocks := make(map[string]map[float64]float64)
	var cur string
	sc := bufio.NewScanner(f)
	rowRe := regexp.MustCompile(`^\s+(\d+):\s+([-\d.]+),`)
	for sc.Scan() {
		line := sc.Text()
		if strings.Contains(line, `": {`) {
			cur = strings.TrimSpace(strings.Split(line, `"`)[1])
			blocks[cur] = map[float64]float64{}
			continue
		}
		if cur == "" {
			continue
		}
		if m := rowRe.FindStringSubmatch(line); m != nil {
			lambda, _ := strconv.ParseFloat(m[1], 64)
			v, _ := strconv.ParseFloat(m[2], 64)
			blocks[cur][lambda] = v
			continue
		}
		// The basis dict closes on a line containing only "    },".
		if strings.HasPrefix(strings.TrimSpace(line), "},") {
			cur = ""
		}
	}
	fatal(sc.Err())

	var rows []sample
	for lambda := 300.0; lambda <= 830.0; lambda += 5 {
		rows = append(rows, sample{
			lambda: lambda,
			vals: []float64{
				blocks["S0"][lambda],
				blocks["S1"][lambda],
				blocks["S2"][lambda],
			},
		})
	}
	return rows
}

func emitDaylight(b *strings.Builder, rows []sample) {
	b.WriteString("var daylightBase = []struct {\n")
	b.WriteString("\tlambda         float64\n\ts0, s1, s2     float64\n}{\n")
	for _, r := range rows {
		fmt.Fprintf(b, "\t{%g, %g, %g, %g},\n",
			r.lambda, r.vals[0], r.vals[1], r.vals[2])
	}
	b.WriteString("}\n\n")
}
