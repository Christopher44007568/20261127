// DrawText renders s at (x, y) using only the bundled glyph table. scale>=1
// enlarges each font pixel into a scale*scale block.
func DrawText(img *image.RGBA, x, y, scale int, s string, c color.Color) {
	s = strings.ToUpper(s)
	cx := x
	for _, r := range s {
		glyph, ok := glyph5x7[r]
		if !ok {
			cx += 6 * scale
			continue
		}
		for row := 0; row < 7; row++ {
			for colIdx := 0; colIdx < 5; colIdx++ {
				if glyph[row]&(1<<(4-colIdx)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						img.Set(cx+colIdx*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		cx += 6 * scale
	}
}
