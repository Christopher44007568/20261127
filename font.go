func drawText(img *image.RGBA, x, y int, text string, c RGB, scale int) {
	if scale < 1 {
		scale = 1
	}
	cursor := x
	for _, r := range text {
		if r == ' ' {
			cursor += 6 * scale
			continue
		}
		g, ok := font5x7[r]
		if !ok {
			cursor += 6 * scale
			continue
		}
		for gy := 0; gy < 7; gy++ {
			for gx := 0; gx < 5; gx++ {
				if g[gy]&(1<<(4-gx)) == 0 {
					continue
				}
				for oy := 0; oy < scale; oy++ {
					for ox := 0; ox < scale; ox++ {
						px := cursor + gx*scale + ox
						py := y + gy*scale + oy
						if image.Pt(px, py).In(img.Rect) {
							setRGB(img, px, py, c)
						}
					}
				}
			}
		}
		cursor += 6 * scale
	}
}
