func TextWidth(text string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len(text) * 4 * scale
}

func (c *Canvas) DrawText(x, y int, text string, scale int, col RGB) {
	if scale < 1 {
		scale = 1
	}
	text = strings.ToUpper(text)
	for i, r := range text {
		glyph, ok := miniFont[r]
		if !ok {
			glyph = miniFont['?']
		}
		gx := x + i*4*scale
		for row := 0; row < 5; row++ {
			for bitX := 0; bitX < 3; bitX++ {
				if glyph[row][bitX] != '1' {
					continue
				}
				c.FillRect(gx+bitX*scale, y+row*scale, scale, scale, col)
			}
		}
	}
}

func (c *Canvas) DrawTitleBar(title, subtitle string) {
	c.FillRect(0, 0, c.W, 42, RGB{12, 17, 23})
	c.DrawText(16, 10, title, 2, RGB{236, 242, 248})
	if subtitle != "" {
		c.DrawText(16, 30, subtitle, 1, RGB{151, 166, 180})
	}
}
