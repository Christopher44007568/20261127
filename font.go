func DrawText(c *Canvas, x, y, scale int, text string, col color.RGBA) {
	text = strings.ToUpper(text)
	for _, r := range text {
		glyph, ok := glyphRows[r]
		if !ok {
			glyph = glyphRows['?']
		}
		for gy := 0; gy < glyphH; gy++ {
			for gx := 0; gx < glyphW; gx++ {
				if glyph[gy][gx] == '#' {
					c.FillRect(x+gx*scale, y+gy*scale, scale, scale, col)
				}
			}
		}
		x += (glyphW + 1) * scale
	}
}

func TextWidth(text string, scale int) int {
	return len(text) * (glyphW + 1) * scale
}
