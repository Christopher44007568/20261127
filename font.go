const fontGlyphW = 5
const fontGlyphH = 7

// textSize returns width,height in pixels for the given integer scale.
func textSize(s string, scale int) (int, int) {
	if scale < 1 {
		scale = 1
	}
	n := len([]rune(s))
	if n == 0 {
		return 0, fontGlyphH * scale
	}
	return (n*(fontGlyphW+1) - 1) * scale, fontGlyphH * scale
}

// drawText draws s with the bitmap font. Coordinates are top-left.
func (c *Canvas) drawText(x, y int, s string, scale int, col RGB) {
	if scale < 1 {
		scale = 1
	}
	s = strings.ToUpper(s)
	cx := x
	for _, r := range s {
		glyph, ok := fontGlyphs[r]
		if !ok {
			if r == ' ' {
				cx += (fontGlyphW + 1) * scale
				continue
			}
			glyph = fontGlyphs['?']
		}
		for row := 0; row < fontGlyphH; row++ {
			line := glyph[row]
			for gx := 0; gx < len(line) && gx < fontGlyphW; gx++ {
				if line[gx] == '#' {
					c.fillRect(cx+gx*scale, y+row*scale, scale, scale, col)
				}
			}
		}
		cx += (fontGlyphW + 1) * scale
	}
}

func (c *Canvas) textCentered(cx, y int, s string, scale int, col RGB) {
	w, _ := textSize(s, scale)
	c.drawText(cx-w/2, y, s, scale, col)
}

func (c *Canvas) textRight(x, y int, s string, scale int, col RGB) {
	w, _ := textSize(s, scale)
	c.drawText(x-w, y, s, scale, col)
}
