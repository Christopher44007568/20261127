const glyphAdvance = 6

func textWidth(s string, scale int) int {
	if len(s) == 0 {
		return 0
	}
	return (len([]rune(s))*glyphAdvance - 1) * scale
}

func textHeight(scale int) int { return 7 * scale }

func drawText(img *image.RGBA, x, y int, s string, scale int, c color.RGBA) {
	s = strings.ToUpper(s)
	cx := x
	for _, r := range s {
		rows, ok := glyph5x7[r]
		if !ok && r != ' ' {
			rows = glyph5x7['?']
			ok = true
		}
		if ok {
			for gy := 0; gy < 7; gy++ {
				for gx := 0; gx < 5; gx++ {
					if rows[gy]&(1<<uint(4-gx)) == 0 {
						continue
					}
					for sy := 0; sy < scale; sy++ {
						for sx := 0; sx < scale; sx++ {
							setPixel(img, cx+gx*scale+sx, y+gy*scale+sy, c)
						}
					}
				}
			}
		}
		cx += glyphAdvance * scale
	}
}
