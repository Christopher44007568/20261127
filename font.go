func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*4 - 1) * scale
}

func drawText(dst *image.RGBA, s string, x, y, scale int, col color.RGBA) {
	s = strings.ToUpper(s)
	cx := x
	for _, r := range s {
		glyph, ok := font3x5[r]
		if !ok {
			glyph = font3x5['?']
		}
		for row := 0; row < 5; row++ {
			line := glyph[row]
			for colIdx := 0; colIdx < 3; colIdx++ {
				if line[colIdx] == '#' {
					fillRect(dst, cx+colIdx*scale, y+row*scale, scale, scale, col)
				}
			}
		}
		cx += 4 * scale
	}
}

func fillRect(dst *image.RGBA, x, y, w, h int, col color.RGBA) {
	b := dst.Bounds()
	x0 := maxInt(x, b.Min.X)
	y0 := maxInt(y, b.Min.Y)
	x1 := minInt(x+w, b.Max.X)
	y1 := minInt(y+h, b.Max.Y)
	for yy := y0; yy < y1; yy++ {
		for xx := x0; xx < x1; xx++ {
			dst.SetRGBA(xx, yy, col)
		}
	}
}
