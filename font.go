func DrawText(cv *Canvas, x, y int, text string, scale int, col RGB) {
	if scale < 1 {
		scale = 1
	}
	text = strings.ToUpper(text)
	cx := x
	for _, r := range text {
		glyph, ok := font3x5[r]
		if !ok {
			glyph = font3x5[' ']
		}
		for row := 0; row < 5; row++ {
			for bit := 0; bit < 3; bit++ {
				if glyph[row][bit] == '#' {
					cv.FillRect(cx+bit*scale, y+row*scale,
						cx+(bit+1)*scale-1, y+(row+1)*scale-1, col)
				}
			}
		}
		cx += 4 * scale
	}
}

func TextWidth(text string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len(text) * 4 * scale
}

func DrawLegendRow(cv *Canvas, x, y int, col RGB, text string, scale int) {
	cv.FillRect(x, y, x+18*scale/2, y+10*scale/2, col)
	DrawText(cv, x+14*scale, y-1, text, scale, RGB{226, 232, 240})
}
