package main

import "fmt"

// builtinGlyphs assembles and validates the ASCII bitmap font.
func builtinGlyphs() map[rune][7]string {
	m := map[rune][7]string{}
	for r, g := range letterGlyphs() {
		m[r] = g
	}
	for r, g := range digitGlyphs() {
		m[r] = g
	}
	for r, g := range punctGlyphs() {
		m[r] = g
	}
	for r, g := range m {
		if len(g) != fontGlyphH {
			panic(fmt.Sprintf("font: glyph %q has %d rows, want %d", r, len(g), fontGlyphH))
		}
		for row, line := range g {
			if len(line) != fontGlyphW {
				panic(fmt.Sprintf("font: glyph %q row %d has width %d (%q), want %d", r, row, len(line), line, fontGlyphW))
			}
		}
	}
	return m
}

