func putPixel(img *image.RGBA, x, y int, c color.RGBA) {
	if x < 0 || y < 0 || x >= img.Rect.Dx() || y >= img.Rect.Dy() {
		return
	}
	if c.A == 255 {
		img.SetRGBA(x, y, c)
		return
	}
	old := img.RGBAAt(x, y)
	a := uint32(c.A)
	ia := 255 - a
	img.SetRGBA(x, y, color.RGBA{
		R: uint8((uint32(c.R)*a + uint32(old.R)*ia) / 255),
		G: uint8((uint32(c.G)*a + uint32(old.G)*ia) / 255),
		B: uint8((uint32(c.B)*a + uint32(old.B)*ia) / 255),
		A: 255,
	})
}

func fillRect(img *image.RGBA, x0, y0, x1, y1 int, c color.RGBA) {
	for y := y0; y < y1; y++ {
		for x := x0; x < x1; x++ {
			putPixel(img, x, y, c)
		}
	}
}

func drawLine(img *image.RGBA, x0, y0, x1, y1 int, c color.RGBA) {
	dx := absInt(x1 - x0)
	dy := -absInt(y1 - y0)
	sx, sy := 1, 1
	if x0 > x1 {
		sx = -1
	}
	if y0 > y1 {
		sy = -1
	}
	err := dx + dy
	for {
		putPixel(img, x0, y0, c)
		if x0 == x1 && y0 == y1 {
			return
		}
		e2 := 2 * err
		if e2 >= dy {
			err += dy
			x0 += sx
		}
		if e2 <= dx {
			err += dx
			y0 += sy
		}
	}
}

func absInt(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

func textWidth(s string, scale int) int {
	if len(s) == 0 {
		return 0
	}
	return len([]rune(s))*6*scale - scale
}

func drawText(img *image.RGBA, x, y int, s string, scale int, c color.RGBA) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range s {
		g, ok := font5x7[r]
		if !ok {
			g = font5x7[' ']
		}
		for row, bits := range g {
			for col := 0; col < 5; col++ {
				if bits&(0x10>>uint(col)) == 0 {
					continue
				}
				fillRect(img, cx+col*scale, y+row*scale,
					cx+(col+1)*scale, y+(row+1)*scale, c)
			}
		}
		cx += 6 * scale
	}
}

func drawTextShadow(img *image.RGBA, x, y int, s string, scale int, c color.RGBA) {
	drawText(img, x+scale, y+scale, s, scale, color.RGBA{A: 210})
	drawText(img, x, y, s, scale, c)
}
