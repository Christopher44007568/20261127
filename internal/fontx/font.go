// Measure returns scaled text width and height.
func Measure(text string, scale int) (int, int) {
	if scale < 1 {
		scale = 1
	}
	if text == "" {
		return 0, GlyphHeight * scale
	}
	return len(text)*Advance*scale - (Advance-GlyphWidth)*scale, GlyphHeight * scale
}

// Draw renders text with top-left baseline coordinates.
func Draw(dst drawImage, x, y int, text string, scale int, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	text = strings.ToUpper(text)
	for i, r := range text {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['?']
		}
		gx := x + i*Advance*scale
		for row := 0; row < GlyphHeight; row++ {
			for col := 0; col < GlyphWidth; col++ {
				if g[row][col] != '1' {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						dst.Set(gx+col*scale+sx, y+row*scale+sy, c)
					}
				}
			}
		}
	}
}

// Centered draws text centered in a rectangle's top coordinate.
func Centered(dst drawImage, cx, y int, text string, scale int, c color.Color) {
	w, _ := Measure(text, scale)
	Draw(dst, cx-w/2, y, text, scale, c)
}

type drawImage interface {
	Set(x, y int, c color.Color)
	Bounds() image.Rectangle
}
