// TextWidth returns the pixel width of s at integer scale.
func TextWidth(s string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len(s) * (glyphW + 1) * scale
}

// DrawText renders s at (x,y) with the top-left anchor and integer scale.
func DrawText(img *image.RGBA, s string, x, y, scale int, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	s = strings.ToUpper(s)
	cx := x
	for i := 0; i < len(s); i++ {
		ch := s[i]
		g, ok := font5x7[ch]
		if !ok {
			g = [glyphH]string{"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"}
		}
		for row := 0; row < glyphH; row++ {
			line := g[row]
			for col := 0; col < glyphW; col++ {
				if col < len(line) && line[col] == '#' {
					for dy := 0; dy < scale; dy++ {
						for dx := 0; dx < scale; dx++ {
							img.Set(cx+col*scale+dx, y+row*scale+dy, c)
						}
					}
				}
			}
		}
		cx += (glyphW + 1) * scale
	}
}

// DrawTextCentered centers s horizontally at cy-top y.
func DrawTextCentered(img *image.RGBA, s string, cx, y, scale int, c color.Color) {
	w := TextWidth(s, scale)
	DrawText(img, s, cx-w/2, y, scale, c)
}
