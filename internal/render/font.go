const (
	glyphW = 5
	glyphH = 7
)

// Text draws a string at x,y (top-left) at the given integer scale.
func (c *Canvas) Text(x, y, scale int, s string, col RGB) {
	for i := 0; i < len(s); i++ {
		g, ok := glyph5x7[s[i]]
		if !ok {
			g = glyph5x7[' ']
		}
		baseX := x + i*(glyphW+2)*scale
		for row := 0; row < glyphH; row++ {
			mask := g[row]
			for bit := 0; bit < glyphW; bit++ {
				if mask&(1<<(glyphW-1-bit)) != 0 {
					c.FillRect(baseX+bit*scale, y+row*scale,
						baseX+(bit+1)*scale, y+(row+1)*scale, col)
				}
			}
		}
	}
}

// TextWidth returns the rendered width of s at the given scale.
func TextWidth(s string, scale int) int {
	return len(s)*(glyphW+2)*scale - scale
}
