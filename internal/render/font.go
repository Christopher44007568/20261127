func TextWidth(s string, scale int) int {
	if scale < 1 {
		scale = 1
	}
	return len(s) * 6 * scale
}

func DrawText(img *image.RGBA, x, y int, s string, scale int, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	rgba := color.RGBAModel.Convert(c).(color.RGBA)
	for i, r := range s {
		g, ok := glyph5x7[r]
		if !ok {
			g = glyph5x7['?']
		}
		for row := 0; row < 7; row++ {
			line := g[row]
			for col := 0; col < len(line) && col < 5; col++ {
				if line[col] != '#' {
					continue
				}
				px := x + (i*6+col)*scale
				py := y + row*scale
				fillRect(img, px, py, scale, scale, rgba)
			}
		}
	}
}

func fillRect(img *image.RGBA, x, y, w, h int, c color.RGBA) {
	b := img.Bounds()
	for yy := y; yy < y+h; yy++ {
		for xx := x; xx < x+w; xx++ {
			if xx < b.Min.X || xx >= b.Max.X || yy < b.Min.Y || yy >= b.Max.Y {
				continue
			}
			img.SetRGBA(xx, yy, c)
		}
	}
}
