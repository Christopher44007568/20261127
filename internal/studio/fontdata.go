package studio

func pl(coords ...float32) polyline {
	if len(coords)%2 != 0 {
		panic("studio: bad glyph polyline")
	}
	p := make(polyline, len(coords)/2)
	for i := range p {
		p[i] = point{X: coords[i*2], Y: coords[i*2+1]}
	}
	return p
}

