func textWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	return (len(text)*6 - 1) * scale
}

func drawText(img *image.RGBA, x, y int, text string, scale int, ink color.RGBA) {
	text = strings.ToUpper(text)
	cursor := x
	for _, ch := range text {
		rows, ok := glyph5x7[ch]
		if !ok {
			rows = glyph5x7[' ']
		}
		for row, pattern := range rows {
			for col, bit := range []byte(pattern) {
				if bit != '#' {
					continue
				}
				drawRect(img, cursor+col*scale, y+row*scale, scale, scale, ink)
			}
		}
		cursor += 6 * scale
	}
}

func drawRect(img *image.RGBA, x, y, w, h int, c color.RGBA) {
	bounds := img.Bounds()
	for py := y; py < y+h; py++ {
		if py < bounds.Min.Y || py >= bounds.Max.Y {
			continue
		}
		for px := x; px < x+w; px++ {
			if px < bounds.Min.X || px >= bounds.Max.X {
				continue
			}
			img.SetRGBA(px, py, c)
		}
	}
}
