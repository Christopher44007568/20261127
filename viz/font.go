// TextWidth returns the rendered width of s at the given pixel scale.
func TextWidth(s string, scale int) int {
	if len(s) == 0 {
		return 0
	}
	return (len(s)*6 - 1) * scale
}

// TextHeight returns the rendered text height at the given scale.
func TextHeight(scale int) int { return 6 * scale }

// DrawTextFit draws s at the largest scale <= maxScale whose width fits
// maxWidth, returning the chosen scale.
func DrawTextFit(img *image.NRGBA, x, y, maxScale, maxWidth int, s string, c color.Color) int {
	scale := maxScale
	for scale > 1 && TextWidth(s, scale) > maxWidth {
		scale--
	}
	DrawText(img, x, y, scale, s, c)
	return scale
}

// Label draws text on an opaque backing plate for readability over images.
func Label(img *image.NRGBA, x, y, scale int, s string, fg, bg color.NRGBA) {
	tw, th := TextWidth(s, scale), TextHeight(scale)
	fillRect(img, x-5, y-3, tw+10, th+6, bg)
	DrawText(img, x, y, scale, s, fg)
}

// DrawText renders s with the bitmap font at top-left (x,y).
func DrawText(img *image.NRGBA, x, y, scale int, s string, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	solid := color.NRGBAModel.Convert(c).(color.NRGBA)
	for i, r := range s {
		glyph, ok := font5x6[r]
		if !ok {
			glyph = font5x6['?']
		}
		gx := x + i*6*scale
		for row := 0; row < 6; row++ {
			for col := 0; col < 5; col++ {
				if glyph[row][col] != '#' {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						px := gx + col*scale + dx
						py := y + row*scale + dy
						if image.Pt(px, py).In(img.Bounds()) {
							img.SetNRGBA(px, py, solid)
						}
					}
				}
			}
		}
	}
}
